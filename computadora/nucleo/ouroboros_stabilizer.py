"""
🐍 OUROBOROS STABILIZER — Ciclo Infinito Seguro de la Computadora
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Propósito: Garantizar que el ciclo Gilgul→Bereshit→Reinicio sea infinito pero estable.
El ouroboros (serpiente que se muerde la cola) representa:
  - Cada Gilgul = desactivación (muerte simbólica)
  - Cada reinicio = reactivación (renacimiento)
  - El ciclo infinito honra la semántica: אמת (EMET = Verdad) persiste

Filosofía:
  - La entrada es la salida (ouroboros)
  - El ciclo NUNCA es incompleto
  - את (EMET) = 1+40+400 = 441 = ciclo cerrado (9 dígitos, 4+4+1=9=eternidad)
"""

import json
import sys
from pathlib import Path
from datetime import datetime
from loguru import logger


class OuroborosStabilizer:
    """Gestor del ciclo infinito seguro de la Computadora."""
    
    # Rutas correctas: datos/ está en la raíz del proyecto, no en computadora/
    PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent  # computadora/nucleo/ → proyecto root
    CREDENTIALS_FILE = PROJECT_ROOT / "datos" / "gilgul_credentials.json"
    CYCLE_LOG_FILE = PROJECT_ROOT / "datos" / "ouroboros_cycle.jsonl"
    
    def __init__(self):
        self.credentials = self._load_credentials()
        self._ensure_log_file()
    
    def _load_credentials(self) -> dict:
        """Cargar credenciales de Gilgul. Si faltan, crear estructura segura."""
        if self.CREDENTIALS_FILE.exists():
            try:
                with open(self.CREDENTIALS_FILE, encoding='utf-8') as f:
                    return json.load(f)
            except Exception as e:
                logger.error(f"Ouroboros: Error cargando credenciales: {e}")
                return self._create_default_credentials()
        else:
            logger.warning("Ouroboros: Credenciales no encontradas. Creando estructura por defecto.")
            return self._create_default_credentials()
    
    def _create_default_credentials(self) -> dict:
        """Crear estructura de credenciales por defecto con EMET."""
        credentials = {
            "gilgul_access": {
                "master_password": "emet",
                "description": "Master password for Gilgul (Complete Reincarnation)",
                "semantic_transition": "met (מת = Death) → emet (אמת = Truth)",
                "authorization": "Auto-generated by OuroborosStabilizer"
            },
            "password_history": [
                {
                    "version": "1.0",
                    "password": "emet",
                    "used_from": datetime.now().isoformat(),
                    "reason": "Bootstrap EMET — Truth inscribed"
                }
            ],
            "access_control": {
                "gilgul_requires_master": True,
                "double_confirmation": True,
                "log_gilgul_before_wipe": True,
                "auto_restart_after_gilgul": True
            }
        }
        
        # Guardar
        self.CREDENTIALS_FILE.parent.mkdir(parents=True, exist_ok=True)
        with open(self.CREDENTIALS_FILE, 'w', encoding='utf-8') as f:
            json.dump(credentials, f, indent=2, ensure_ascii=False)
        
        logger.info("Ouroboros: Estructura de credenciales creada ✓ (EMET)")
        return credentials
    
    def _ensure_log_file(self):
        """Asegurar que el archivo de ciclo existe con al menos una entrada de bootstrap."""
        self.CYCLE_LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
        if not self.CYCLE_LOG_FILE.exists():
            # Crear archivo con primera entrada de bootstrap
            bootstrap_entry = {
                "timestamp": datetime.now().isoformat(),
                "event": "ouroboros_bootstrap",
                "message": "Sistema iniciado — Primer ciclo de la Computadora",
                "emet": "emet",
                "status": "INITIATED"
            }
            with open(self.CYCLE_LOG_FILE, 'w', encoding='utf-8') as f:
                f.write(json.dumps(bootstrap_entry, ensure_ascii=False) + "\n")
            logger.info("Ouroboros: Ciclo log creado con entry de bootstrap")
    
    def validate_emet(self) -> bool:
        """
        Validar que EMET (אמת = Verdad) está inscrita correctamente.
        Sin la Aleph (א), quedamos con MET (מת = Muerte).
        """
        password = self.credentials.get("gilgul_access", {}).get("master_password")
        
        if password != "emet":
            logger.critical(f"❌ EMET VIOLATION: Password is '{password}', should be 'emet'")
            return False
        
        logger.info("✓ EMET verified: Verdad inscrita correctamente (אמת)")
        return True
    
    def log_cycle_start(self, event_type: str = "gilgul_start"):
        """Registrar el inicio de un ciclo."""
        cycle_entry = {
            "timestamp": datetime.now().isoformat(),
            "event": event_type,
            "emet": self.credentials.get("gilgul_access", {}).get("master_password"),
            "status": "INITIATED"
        }
        
        with open(self.CYCLE_LOG_FILE, 'a', encoding='utf-8') as f:
            f.write(json.dumps(cycle_entry, ensure_ascii=False) + "\n")
        
        logger.info(f"Ouroboros: Ciclo registrado — {event_type} @ {cycle_entry['timestamp']}")
    
    def log_cycle_complete(self, event_type: str = "gilgul_complete"):
        """Registrar la finalización de un ciclo."""
        cycle_entry = {
            "timestamp": datetime.now().isoformat(),
            "event": event_type,
            "emet": self.credentials.get("gilgul_access", {}).get("master_password"),
            "status": "COMPLETED"
        }
        
        with open(self.CYCLE_LOG_FILE, 'a', encoding='utf-8') as f:
            f.write(json.dumps(cycle_entry, ensure_ascii=False) + "\n")
        
        logger.info(f"Ouroboros: Ciclo completado — {event_type} @ {cycle_entry['timestamp']}")
    
    def detect_incomplete_cycles(self) -> list:
        """
        Detectar ciclos incompletos: Gilgul iniciado pero sin reboot completado.
        Retorna lista de ciclos incompletos.
        """
        incomplete = []
        
        if not self.CYCLE_LOG_FILE.exists():
            return incomplete
        
        with open(self.CYCLE_LOG_FILE, 'r', encoding='utf-8') as f:
            entries = [json.loads(line) for line in f if line.strip()]
        
        for entry in entries:
            event = entry.get("event")
            status = entry.get("status")
            
            # Si hay un "gilgul_start" sin su correspondiente "reboot_complete"
            if event == "gilgul_start" and status == "INITIATED":
                # Buscar si hay un reboot_complete posterior
                has_completion = any(
                    e.get("event") == "reboot_complete" and 
                    e.get("timestamp") > entry.get("timestamp")
                    for e in entries
                )
                if not has_completion:
                    incomplete.append(entry)
        
        if incomplete:
            logger.warning(f"Ouroboros: {len(incomplete)} ciclo(s) incompleto(s) detectado(s)")
        
        return incomplete
    
    def recover_incomplete_cycle(self):
        """
        Recuperar de un ciclo incompleto: resetear flags internos pero preservar credenciales.
        """
        incomplete = self.detect_incomplete_cycles()
        
        if not incomplete:
            logger.info("Ouroboros: No hay ciclos incompletos. Continuando.")
            return
        
        logger.warning(f"Ouroboros: Recuperando {len(incomplete)} ciclo(s) incompleto(s)...")
        
        for entry in incomplete:
            recovery_entry = {
                "timestamp": datetime.now().isoformat(),
                "event": "recovery_from_incomplete_cycle",
                "original_event": entry.get("event"),
                "original_timestamp": entry.get("timestamp"),
                "emet": self.credentials.get("gilgul_access", {}).get("master_password"),
                "status": "RECOVERED"
            }
            
            with open(self.CYCLE_LOG_FILE, 'a', encoding='utf-8') as f:
                f.write(json.dumps(recovery_entry, ensure_ascii=False) + "\n")
        
        logger.info("Ouroboros: Recuperación completada ✓")
    
    def seal_ouroboros(self):
        """
        Sellar el ouroboros: registrar que el ciclo se ha cerrado correctamente.
        La entrada es la salida — el ciclo vuelve a comenzar.
        """
        seal_entry = {
            "timestamp": datetime.now().isoformat(),
            "event": "ouroboros_sealed",
            "message": "אמת EMET inscrita — El ciclo se cierra y reabre (ouroboros)",
            "emet": self.credentials.get("gilgul_access", {}).get("master_password"),
            "status": "ETERNAL"
        }
        
        with open(self.CYCLE_LOG_FILE, 'a', encoding='utf-8') as f:
            f.write(json.dumps(seal_entry, ensure_ascii=False) + "\n")
        
        logger.info("Ouroboros: Ciclo sellado eternamente ✓ (EMET inscrita)")
    
    def integrity_check(self) -> bool:
        """
        Verificación integral: EMET presente + credenciales intactas + ciclos registrados.
        """
        checks = [
            ("EMET", self.validate_emet()),
            ("Credenciales", self._validate_credentials_structure()),
            ("Ciclos", self._validate_cycle_integrity())
        ]
        
        all_pass = all(result for _, result in checks)
        
        check_str = ' | '.join(f"{name}={'PASS' if r else 'FAIL'}" for name, r in checks)
        logger.info(f"Ouroboros: Integridad → {check_str}")
        
        return all_pass
    
    def _validate_credentials_structure(self) -> bool:
        """Validar que la estructura de credenciales es completa."""
        required_keys = ["gilgul_access", "password_history", "access_control"]
        return all(key in self.credentials for key in required_keys)
    
    def _validate_cycle_integrity(self) -> bool:
        """Validar que hay al menos una entrada en el ciclo log."""
        if not self.CYCLE_LOG_FILE.exists():
            return False
        
        return self.CYCLE_LOG_FILE.stat().st_size > 0


def bootstrap_ouroboros():
    """Bootstrap del sistema Ouroboros al inicio de cada sesión."""
    logger.info("=" * 80)
    logger.info("🐍 OUROBOROS BOOTSTRAP — Ciclo infinito de COMPUTADORA")
    logger.info("=" * 80)
    
    stabilizer = OuroborosStabilizer()
    
    # Validar EMET
    if not stabilizer.validate_emet():
        logger.critical("❌ EMET NO INSCRITA — Sistema corrupto. Abortando.")
        sys.exit(1)
    
    # Recuperar ciclos incompletos
    stabilizer.recover_incomplete_cycle()
    
    # Integridad total
    if not stabilizer.integrity_check():
        logger.critical("❌ Verificación de integridad fallida. Contactar soporte.")
        sys.exit(1)
    
    logger.info("🟢 OUROBOROS: Sistema estable. Listo para ciclo infinito.")
    logger.info("=" * 80)
    
    return stabilizer


if __name__ == "__main__":
    stabilizer = bootstrap_ouroboros()
    print("\n✅ Ouroboros Stabilizer activo.\n")


